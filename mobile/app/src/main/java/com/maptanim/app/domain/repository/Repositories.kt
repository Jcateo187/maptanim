package com.maptanim.app.domain.repository

import com.maptanim.app.domain.model.*
import kotlinx.coroutines.flow.Flow

// ─── FarmRepository ────────────────────────────────────────────────────────

/**
 * Contract for farm data operations.
 * Implementation in data/repository/FarmRepositoryImpl.kt
 * All reads return Flow from Room (offline-first).
 * All writes go to Room first, then enqueue to SyncQueue.
 */
interface FarmRepository {
    fun observeFarms(farmerId: String): Flow<List<Farm>>
    fun observeFarm(farmId: String): Flow<Farm?>
    suspend fun upsertFarm(farm: Farm)
    suspend fun deleteFarm(farmId: String)
}

// ─── BedRepository ─────────────────────────────────────────────────────────

/**
 * Contract for bed (planting plot) data operations.
 * Source of truth: Room DB (synced from Supabase beds table).
 * Write path: Room → SyncQueue → SyncWorker → Supabase PATCH/POST/DELETE.
 */
interface BedRepository {
    /** Live stream of all active beds for a farm. Sourced from Room. */
    fun observeBeds(farmId: String): Flow<List<Bed>>

    /** Live stream of a single bed by ID. */
    fun observeBed(bedId: String): Flow<Bed?>

    /** Observe all beds across all farms for the current farmer (used by Calendar). */
    fun observeAllBedsWithCrop(farmerId: String): Flow<List<Bed>>

    /**
     * Persist updated beds (positions, soil, crop) to Room and enqueue sync.
     * Called by SaveFarmLayoutUseCase after SAVE CHANGES in Edit Mode.
     */
    suspend fun saveBeds(beds: List<Bed>)

    /** Soft-delete a bed (isActive = false) and enqueue Supabase DELETE. */
    suspend fun deleteBed(bedId: String)

    /** Upsert a single bed (used after Add Bed in Edit Mode). */
    suspend fun upsertBed(bed: Bed)
}

// ─── TaskRepository ────────────────────────────────────────────────────────

/**
 * Contract for DSS-generated task data.
 * Tasks are generated by the evaluate-dss Edge Function and stored in Supabase tasks table,
 * then synced to Room by SyncWorker / AppInitializationController.
 */
interface TaskRepository {
    /** Today's incomplete tasks for a farm. Drives TODAY'S TASKS panel and status pins. */
    fun observeTodayTasks(farmId: String, today: String): Flow<List<FarmTask>>

    /** All tasks for all farms owned by the farmer (used by Calendar screen). */
    fun observeAllTasks(farmerId: String): Flow<List<FarmTask>>

    /** Tasks within a date range (Calendar monthly view). */
    fun observeTasksForRange(farmerId: String, startDate: String, endDate: String): Flow<List<FarmTask>>

    /** Active alerts (PEST_ALERT, WARNING) — drives FARM SUMMARY "Active Alerts" count. */
    fun observeActiveAlerts(farmId: String): Flow<List<FarmTask>>

    /** HARVEST tasks — drives "Ready to Harvest" count in FARM SUMMARY. */
    fun observeHarvestReady(farmId: String): Flow<List<FarmTask>>

    /** Mark a task as completed. Updates Room immediately, enqueues Supabase PATCH. */
    suspend fun completeTask(taskId: String, completedAt: String)

    /** Upsert tasks received from evaluate-dss Edge Function response. */
    suspend fun upsertTasks(tasks: List<FarmTask>)
}

