// ─── SyncRepository ────────────────────────────────────────────────────────

/**
 * Contract for the offline sync queue.
 * SyncWorker reads from this repository to determine pending Supabase operations.
 */
interface SyncRepository {
    suspend fun enqueueSyncItem(tableName: String, recordId: String, operation: String, payload: String)
    suspend fun getPendingItems(): List<SyncQueueItem>
    suspend fun markSynced(itemId: String)
    suspend fun markFailed(itemId: String, lastAttemptAt: String)
    suspend fun hasPendingItems(): Boolean
}

data class SyncQueueItem(
    val id: String,
    val tableName: String,
    val recordId: String,
    val operation: String,  // "INSERT" | "UPDATE" | "DELETE"
    val payload: String,    // JSON
    val status: String,
    val attemptCount: Int
)

