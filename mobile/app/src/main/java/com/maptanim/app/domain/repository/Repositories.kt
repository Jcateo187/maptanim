// ─── NotificationRepository ────────────────────────────────────────────────

/**
 * Contract for notification data.
 * The notification badge count (e.g., "3" in the top bar) is driven by
 * observeUnreadCount() — never a hardcoded value.
 */
interface NotificationRepository {
    fun observeAllNotifications(userId: String): Flow<List<Notification>>

    /** Drives the 🔔 badge count in the top bar. Emits live count from Room. */
    fun observeUnreadCount(userId: String): Flow<Int>

    suspend fun markRead(notificationId: String)
    suspend fun markAllRead(userId: String)
    suspend fun upsertNotifications(notifications: List<Notification>)
}

